package org.aston.prod.additionalTasks.task3;

import java.util.function.Consumer;

/**
 * Общий интерфейс для работы с коллекциями элементов произвольного типа.
 * Определяет базовый набор операций, которые должны поддерживаться любой реализацией коллекции.
 *
 * @param <S> тип элементов, хранящихся в коллекции
 */

public interface ICollection<S> {

    /**
     * Возвращает количество элементов в коллекции.
     *
     * @return количество элементов в коллекции; 0, если коллекция пуста
     */

    int length();

    /**
     * Проверяет, является ли коллекция пустой.
     *
     * @return {@code true}, если коллекция не содержит элементов;
     *         {@code false}, если в коллекции есть хотя бы один элемент
     */

    boolean isEmpty();

    /**
     * Добавляет элемент в коллекцию.
     *
     * @param element элемент, который нужно добавить в коллекцию
     *
     * @return {@code true}, если элемент успешно добавлен;
     *         {@code false}, если добавление не удалось (например, из‑за ограничений реализации)
     */

    boolean add(S element);

    /**
     * Удаляет указанный элемент из коллекции.
     * Если в коллекции несколько одинаковых элементов, может быть удалён только один из них.
     *
     * @param element элемент, который нужно удалить из коллекции
     *
     * @return {@code true}, если элемент был найден и успешно удалён;
     *         {@code false}, если элемент не найден в коллекции
     */

    boolean remove(S element);

    /**
     * Полностью очищает коллекцию, удаляя все элементы.
     * После вызова этого метода коллекция становится пустой ({@link #isEmpty()} вернёт {@code true}).
     */

    void removeAll();

    /**
     * Применяет заданное действие ко всем элементам коллекции.
     * Позволяет выполнить итерацию по элементам без явного использования циклов.
     *
     * @param consumer объект {@link Consumer}, определяющий действие, которое будет применено
     *               к каждому элементу коллекции
     */

    void forEach(Consumer<S> consumer);
}
