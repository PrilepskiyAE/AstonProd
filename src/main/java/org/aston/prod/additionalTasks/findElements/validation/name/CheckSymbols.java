package org.aston.prod.additionalTasks.findElements.validation.name;

import java.util.List;

/**
 * Класс проверки имени студента на наличие только буквенных символов.
 * Реализует часть цепочки проверок в рамках паттерна «Цепочка обязанностей» (Chain of Responsibility).
 *
 * <p>Проверяет, что имя состоит исключительно из букв (включая буквы разных языков и алфавитов),
 * без цифр, знаков препинания и других специальных символов. При обнаружении недопустимых
 * символов в список ошибок добавляется соответствующее сообщение.</p>
 */

public class CheckSymbols extends CheckName {

    /**
     * Проверяет, что имя содержит только буквенные символы.
     *
     * Алгоритм работы:
     * 1. Использует регулярное выражение {@code "^\\p{L}+$"} для проверки всей строки:
     *    - {@code ^} — начало строки;
     *    - {@code \\p{L}} — любой буквенный символ (Unicode, включая кириллицу, латиницу и др.);
     *    - {@code +} — один или более повторений;
     *    - {@code $} — конец строки.
     * 2. Если строка не соответствует шаблону (содержит небуквенные символы),
     *    добавляет в список {@code errors} сообщение: «Имя должно содержать только буквы».
     *
     * @param value  имя студента для проверки (предполагается, что строка не null и не пустая)
     * @param errors список для накопления сообщений об ошибках валидации.
     *              Если имя содержит недопустимые символы, в список добавляется описание ошибки.
     *
     */
    @Override
    void validName(String value, List<String> errors) {
        if (!(value.matches("^\\p{L}+$"))) {
            errors.add("Имя должно содержать только буквы");
        }
    }
}
