package org.aston.prod.additionalTasks.findElements.validation.name;

import java.util.List;

/**
 * Класс проверки длины имени студента. Реализует часть цепочки проверок в рамках паттерна
 * «Цепочка обязанностей» (Chain of Responsibility).
 *
 * <p>Проверяет, что длина имени находится в допустимом диапазоне: от 3 до 11 символов
 * включительно. Если длина выходит за эти границы, в список ошибок добавляется соответствующее
 * сообщение.</p>
 *
 * @see CheckName
 */

public class CheckLong extends CheckName{

    /**
     * Проверяет длину имени студента на соответствие допустимому диапазону.
     *
     * Алгоритм работы:
     * 1. Получает длину строки {@code value} с помощью метода {@code length()}.
     * 2. Сравнивает длину с граничными значениями:
     *    - минимальное допустимое значение — 3 символа;
     *    - максимальное допустимое значение — 11 символов.
     * 3. Если длина строки меньше 3 или больше 11, добавляет в список {@code errors}
     *    сообщение: «Имя должно содержать от 3 до 11 символов».
     *
     * @param value  имя студента для проверки (предполагается, что строка не null)
     * @param errors список для накопления сообщений об ошибках валидации.
     *              Если имя не соответствует критерию длины, в список добавляется описание ошибки.
     *
     * @throws NullPointerException если параметр {@code value} равен {@code null}.
     *                            Метод предполагает, что входная строка валидирована
     *                            на null до вызова (например, в классе {@link Validation})
     *
     * @see String#length()
     */

    @Override
    void validName(String value, List<String> errors) {
        int length = value.length();
        if (length < 3 || length > 11) {
            errors.add("Имя должно содержать от 3 до 11 символов");
        }
    }
}
