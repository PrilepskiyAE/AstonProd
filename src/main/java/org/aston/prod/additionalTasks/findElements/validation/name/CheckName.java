package org.aston.prod.additionalTasks.findElements.validation.name;

import java.util.List;

/**
 * Абстрактный класс, реализующий звено в цепочке проверок имени студента
 * (паттерн «Цепочка обязанностей» / Chain of Responsibility).
 *
 * <p>Определяет базовую структуру для последовательной валидации имени:
 * каждое звено выполняет свою проверку, а затем передаёт запрос следующему звену
 * в цепочке, если оно существует.</p>
 *
 * <p>Конкретные правила валидации реализуются в подклассах через метод {@link #validName}.</p>
 */

public abstract class CheckName {
    private CheckName nextCheckName;

    /**
     * Устанавливает следующее звено в цепочке проверок.
     *
     * @param nextCheckName объект {@code CheckName}, который будет выполнять
     *                      следующую проверку в цепочке после текущей
     *
     * @return ссылка на переданный объект {@code nextCheckName}, что позволяет
     *         выстраивать цепочку вызовов в стиле «fluent interface»
     *         (например: {@code check1.setNextCheckName(check2).setNextCheckName(check3)})
     */

    public CheckName setNextCheckName(CheckName nextCheckName) {
        this.nextCheckName = nextCheckName;
        return nextCheckName;
    }

    /**
     * Выполняет проверку имени и передаёт запрос следующему звену в цепочке (если есть).
     *
     * Алгоритм работы:
     * 1. Вызывает абстрактный метод {@link #validName} для выполнения специфичной
     *    проверки текущего звена.
     * 2. Если в цепочке есть следующее звено ({@code nextCheckName != null}),
     *    передаёт ему тот же запрос ({@code value}, {@code errors}) для дальнейшей проверки.
     *
     * <p>Таким образом обеспечивается последовательное выполнение всех проверок
     * в заданной цепочке.</p>
     *
     * @param value  имя студента для проверки
     * @param errors список для накопления сообщений об ошибках валидации.
     *              Каждый этап проверки может добавить свои сообщения в этот список.
     */

    public void check(String value, List<String> errors) {
        validName(value, errors);
        if (nextCheckName != null) {
            nextCheckName.check(value, errors);
        }
    }

    /**
     * Абстрактный метод для реализации конкретной логики валидации имени.
     *
     * <p>Должен быть переопределён в каждом подклассе {@code CheckName} для реализации
     * специфичного правила проверки (например, проверка длины, первой буквы, допустимых символов).</p>
     *
     * <p>При обнаружении нарушения правила метод должен добавить соответствующее сообщение
     * об ошибке в список {@code errors}.</p>
     *
     * @param value  имя студента для проверки (может предполагать предварительную валидацию
     *              на {@code null} и пустоту в вышестоящих компонентах)
     * @param errors список для добавления сообщений об ошибках. Если проверка не пройдена,
     *              метод должен добавить в этот список описание проблемы
     */

    abstract void validName(String value, List<String> errors);
}
